def render_bitmap(b):
    print("Bitmap_F0D5BF_80x24 -- %d columns x %d rows, column-major" % (BM_COLS, BM_ROWS))
    for r in range(BM_ROWS):
        line = ""
        for c in range(BM_COLS):
            v = at(b, BM_START + c * BM_ROWS + r, 1)[0]
            line += "".join("#" if (v >> (7 - i)) & 1 else "." for i in range(8))
        print("  %2d %s" % (r, line))


def main():
    b = rom()

    if "--render" in sys.argv:
        render_bitmap(b)
        return 0

    if "--selftest" in sys.argv:
        print("gen_promB3_spans.py --selftest")
        # span 1: the six +7 pointers, and the extents they force
        for rec, tgt in ((0xF0D4BC, 0xF0D4D2), (0xF0D4C7, 0xF0D4D2),
                         (0xF0D51A, 0xF0D530), (0xF0D525, 0xF0D530),
                         (0xF0D578, 0xF0D58E), (0xF0D583, 0xF0D58E),
                         (0xF2B42F, 0xF2B445), (0xF2B43A, 0xF2B445),
                         (0xF2B4C5, 0xF2B4D0), (0xF2BB0D, 0xF2BB18)):
            d = at(b, rec, 11)
            check("0x%06X is op 03/08 len 11" % rec, (d[0] in (3, 8), d[1]), (True, 11))
            check("0x%06X +7 long" % rec, "0x%06X" % w32(b, rec + 7), "0x%06X" % tgt)
        for tbl, nxt in ((0xF0D4D2, 0xF0D51A), (0xF0D530, 0xF0D578), (0xF0D58E, 0xF0D59E),
                         (0xF2B445, 0xF2B4C5), (0xF2B4D0, 0xF2B510), (0xF2BB18, 0xF2BD18)):
            check("table 0x%06X extent is a whole number of 8-byte entries" % tbl,
                  (nxt - tbl) % 8, 0)
        # span 4 only: the mask-implied count EQUALS the extent
        d = at(b, 0xF2BB0D, 11)
        check("0xF2BB0D mask/shift imply exactly the extent",
              ((d[4] >> (d[5] & 7)) + 1) * 8, 0xF2BD18 - 0xF2BB18)
        # span 1: the ramp
        check("0xF0D59E is the ramp 0x01..0x21",
              list(at(b, 0xF0D59E, 33)), list(range(1, 34)))
        # span 1: the bitmap's alignment and its end
        check("bitmap 0xF0D5BF + 10*24 ends at the op-23 record",
              "0x%06X" % (BM_START + BM_COLS * BM_ROWS), "0x%06X" % 0xF0D6AF)
        check("0xF0D6AF is op 23 len 5 (handler 0xF31ACE, implied 5)",
              tuple(at(b, 0xF0D6AF, 2)), (0x23, 0x05))
        check("and it lands on the converted record at 0xF0D6B4",
              "0x%06X" % (0xF0D6AF + 5), "0x%06X" % 0xF0D6B4)
        cand = [a for a in range(0xF0D59E, 0xF0D5C0) if (0xF0D6AF - a) % 24 == 0]
        check("only two 24-aligned starts clear the 2-entry table",
              ["0x%06X" % a for a in cand], ["0x%06X" % 0xF0D5A7, "0x%06X" % 0xF0D5BF])
        check("the lower one, 0xF0D5A7, falls strictly inside the 0x01..0x21 ramp",
              0xF0D59E < 0xF0D5A7 < 0xF0D59E + 33, True)
        # span 2: the walk, the pointer tables, the two characters
        recs = DL.walk(b, 0xF0D7E2, 0xF0D942)
        check("0xF0D7E2 walks to 0xF0D942 with zero drift", recs is not None, True)
        check("all 16 records are op 07", sorted({op for _p, op, _l in recs}), [7])
        starts = {p for p, _o, _l in recs}
        for tbl in (0xF0D942, 0xF0D96E):
            vals = [w32(b, tbl + i * 4) for i in range(11)]
            check("0x%06X entry [0] is 0" % tbl, vals[0], 0)
            check("0x%06X entries 1-10 are all record starts" % tbl,
                  sorted({v in starts for v in vals[1:]}), [True])
        check("the two tables end exactly on Chars_F0D99A",
              "0x%06X" % (0xF0D942 + 22 * 4), "0x%06X" % 0xF0D99A)
        check("Chars_F0D99A leaves 0 bytes before DL_F0D99C",
              0xF0D99C - (0xF0D99A + 2), 0)
        # span 3: the word array seam, the pointer table, the five arrays
        arr = [w16(b, 0xF2B41F + i * 2) for i in range(8)]
        check("0xF2B41F is 8 words stepping 0x320",
              sorted({arr[i + 1] - arr[i] for i in range(7)}), [0x320])
        ptrs = [w32(b, 0xF2B510 + i * 4) for i in range(10)]
        check("DLPtrTable_F2B510 holds 5 distinct targets",
              ["0x%06X" % v for v in sorted(set(ptrs))],
              ["0x%06X" % v for v in (0xF2B538, 0xF2B53C, 0xF2B544, 0xF2B550, 0xF2B560)])
        tg = sorted(set(ptrs)) + [0xF2B574]
        check("the five arrays tile 0xF2B538-0xF2B573 with no slack",
              [tg[i + 1] - tg[i] for i in range(5)], [4, 8, 12, 16, 20])
        # every span's pieces add up to the span
        for s, e, parts in ((0xF0D4D2, 0xF0D698, [72, 11, 11, 72, 11, 11, 16, 33, 217]),
                            (0xF0D7E2, 0xF0D99C, [352, 44, 44, 2]),
                            (0xF2B422, 0xF2B574, [13, 11, 11, 128, 11, 64, 40, 60]),
                            (0xF2BB0D, 0xF2BD18, [11, 512])):
            check("0x%06X pieces sum to the span" % s, sum(parts), e - s)
        print("FAILURES: %d" % len(FAIL))
        return 1 if FAIL else 0

    if "--show" in sys.argv:
        for _old, fn in EDITS:
            sys.stdout.write("".join(fn(b)))
        sys.stdout.write("".join(d698_fix(b)))
        return 0

    if "--splice" in sys.argv:
        path = os.path.join(ROOT, S_FILE)
        cur = open(path, "rb").read()                 # bytes: these sources are latin-1
        before = len(cur)
        for old, fn in EDITS:
            o = old.encode("utf-8")
            if cur.count(o) != 1:
                raise SystemExit("expected exactly one %r, found %d" % (old[:60], cur.count(o)))
            cur = cur.replace(o, "".join(fn(b)).encode("utf-8"), 1)
        for old, new in ((D698_OLD, "".join(d698_fix(b))), (HDR_OLD, HDR_NEW)):
            o = old.encode("utf-8")
            if cur.count(o) != 1:
                raise SystemExit("expected exactly one %r, found %d" % (old[:60], cur.count(o)))
            cur = cur.replace(o, new.encode("utf-8"), 1)
        tmp = path + ".tmp%d" % os.getpid()
        open(tmp, "wb").write(cur)
        os.replace(tmp, path)
        print("spliced 4 spans (1,757 bytes) + the 0xF0D698 correction; %d -> %d bytes"
              % (before, len(cur)))
        return 0

    print("pass --selftest, --render, --show or --splice")
    return 1


if __name__ == "__main__":
    sys.exit(main())
