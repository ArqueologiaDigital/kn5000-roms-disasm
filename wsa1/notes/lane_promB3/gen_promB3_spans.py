#!/usr/bin/env python3
"""Emit lane promB3's four prom_b spans as real source, and prove the framing.

QUESTION ANSWERED
  What is in prom_b's four remaining `.incbin` spans 0xF0D4D2+454,
  0xF0D7E2+442, 0xF2B422+338 and 0xF2BB0D+523 (1,757 bytes), and what says so?

  All four are display-list DATA, not code.  Nothing in any of the four images
  branches into them; what names them are POINTERS -- the `+7` field of an
  interpreter-B record, a `ld XIY/XIX/XIZ` immediate in prom_a, or an entry of
  a pointer table inside the span itself.  Every object below is typed, and its
  EXTENT is forced by the next named address, not chosen.

  The pointer evidence is regenerated by notes/lane_promB3/xref_scan.py; the
  record framing by --selftest here.

THE FOUR SPANS
  0xF0D4D2 +454  three 8-byte-entry operand tables with the four interpreter-B
                 records that point at them interleaved, a 33-byte ramp, and
                 the first 217 bytes of an 80x24 bitmap that runs 23 bytes past
                 the span's end.
  0xF0D7E2 +442  16 interpreter-A op-07 text records, two 11-entry tables of
                 4-byte pointers INTO those records, and 2 character codes.
  0xF2B422 +338  the tail of a word array, three interpreter-B records, two
                 8-byte-entry tables, a 10-entry pointer table and the five
                 word arrays it points at.
  0xF2BB0D +523  one interpreter-B record and the 64-entry, 8-byte table its
                 own AND mask sizes EXACTLY.

WHY THE 0xF0D698 RECORD IS REWRITTEN TOO
  The bitmap that starts at 0xF0D5BF is 240 bytes and ends at 0xF0D6AF.  The 23
  bytes past this span's end were framed as the operand run of an `op 0C, 28
  bytes` record at 0xF0D698 whose handler (0xF31AEB) is a bare `ret` -- it reads
  nothing, so ANY length "fits" and the framing asserted nothing.  Dropping it
  moves the walk start from +454 to +477 and the first real record becomes the
  `op 23, 5 bytes` glyph record at 0xF0D6AF, which lands on 0xF0D6B4 -- the same
  zero-drift walk, 22 records instead of 23.  gen_prom_b_untouched_pool_module.py
  states this exact hazard about a DIFFERENT span and then admits offset 454
  here because it only required SOME record to be non-weak, not the first.

RUN
  python3 notes/lane_promB3/gen_promB3_spans.py --selftest   # the framing checks
  python3 notes/lane_promB3/gen_promB3_spans.py --render     # the bitmap, as pixels
  python3 notes/lane_promB3/gen_promB3_spans.py --show       # the assembly
  python3 notes/lane_promB3/gen_promB3_spans.py --splice     # into prom_b/wsa1_prom_b.s
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "scripts", "analysis"))
import prom_b_display_lists as DL              # noqa: E402

B_BASE = 0xF00000
ROM = "original_ROMs/wsa1_prom_b.ic13"
S_FILE = "prom_b/wsa1_prom_b.s"

BM_START, BM_COLS, BM_ROWS = 0xF0D5BF, 10, 24   # the bitmap that straddles 0xF0D698
FAIL = []


def rom():
    return open(os.path.join(ROOT, ROM), "rb").read()


def at(b, a, n):
    return b[a - B_BASE:a - B_BASE + n]


def w16(b, a):
    return int.from_bytes(at(b, a, 2), "little")


def w32(b, a):
    return int.from_bytes(at(b, a, 4), "little")


def check(msg, got, want):
    ok = got == want
    print("  %-72s %-22s %s" % (msg, got, "OK" if ok else "FAIL want %s" % (want,)))
    if not ok:
        FAIL.append(msg)


# ---------------------------------------------------------------- emitters --

def b_record(b, p, target_sym):
    """One interpreter-B op 03/08 record, len 11, handler 0xF31B57.

    Field names are FINDINGS-ui-display-list-interpreter-b.md's, and the
    spelling is the one DL_F2B379 in this file already uses."""
    d = at(b, p, 11)
    return ["\t.byte 0x%02X, 0x0B\t; B op %02X, 11 bytes -> handler 0xF31B57 -- four words of entry[value] -> (0x2530..0x2536)\n"
            % (d[0], d[0]),
            "\t.short 0x%04X\t; +0x02 source variable, 16-bit address\n" % (d[2] | d[3] << 8),
            "\t.byte 0x%02X\t; +0x04 AND mask\n" % d[4],
            "\t.byte 0x%02X\t; +0x05 right shift, low 3 bits\n" % d[5],
            "\t.byte 0x%02X\t; +0x06 swi 7 function\n" % d[6],
            "\t.long %s\t; +0x07 -> XIX: array of 8-byte entries, indexed by the value\n" % target_sym]


def table8(b, p, n, label):
    out = ["%s:\n" % label]
    for i in range(n):
        e = at(b, p + i * 8, 8)
        w = [int.from_bytes(e[k * 2:k * 2 + 2], "little") for k in range(4)]
        out.append("\t.short 0x%04X, 0x%04X, 0x%04X, 0x%04X\t; [%d]\n" % (*w, i))
    return out


def byte_rows(b, p, n, per=12, tag=""):
    out = []
    for o in range(0, n, per):
        raw = at(b, p + o, min(per, n - o))
        out.append("\t.byte %s\t; %06X%s\n"
                   % (", ".join("0x%02X" % c for c in raw), p + o, tag))
    return out


