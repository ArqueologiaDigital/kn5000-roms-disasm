MidiPkt_ExtractAndPack:
	; --- Stack-frame: XIZ struct field extraction + packed lookup (96 bytes) ---
	lda	xsp, (xsp-16)
	push xiz
	ld xiz, xwa
	ld a, (xiz+6)
	ld c, (xiz+7)
	call Part_LookupTableEntry
	extz hl
	ld (xsp+4), hl
	ld a, (xiz+6)
	ld c, (xiz+7)
	inc 1, c
	call Part_LookupTableEntry
	extz hl
	sll	hl, 8
	or (xsp+4), hl
	lda	xbc, (xsp+14)
	ld a, (xiz+6)
	ld (xbc), a
	ld a, (xiz+7)
	ld (xbc+1), a
	ld wa, (xsp+4)
	ld (xbc+2), wa
	ld e, (xiz+8)
	extz de
	ld a, (xiz+0x0b)
	and a, 0x0f
	jr z, MidiPkt_ExtractAndPack_StoreShifted
	.byte 0xda, 0xfe				; sll a, de  [shift by register count]
MidiPkt_ExtractAndPack_StoreShifted:
	ld (xbc+4), de
	lda	xwa, (xsp+6)
	ld (xwa), xbc
	ld (xwa+4), xiz
	calr MidiPkt_EnqueueExtended_Data
	pop xiz
	lda	xsp, (xsp+16)
	ret
MidiPkt_ExtractAndPack_Ret:
	ret


