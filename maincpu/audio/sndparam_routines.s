SndParam_RW_ChainCheckFirst:
	cp hl, 0xFFFF
	jr z, SndParam_RW_ChainContinue

SndParam_RW_FoundCallback:
	ld xwa, (xde + 4)
	jr SndParam_RW_ProcessResult

SndParam_RW_ChainContinue:
	ld xwa, (xde + 8)
	or xwa, xwa
	jr nz, SndParam_RW_ChainNext

SndParam_RW_NoEntry:
	lds32 xwa, 0

SndParam_RW_ProcessResult:
	ld xiz, xwa
	or xwa, xwa
	jr z, SndParam_RW_Fail
	ld xwa, (xsp + 18)
	ld xbc, (xiz)
	ld (xwa), xbc
	ld xwa, (xsp + 22)
	cp (xwa), 0xB1
	jr z, SndParam_RW_HandleB1Type
	ld a, (xiz + 15)
	inc 3, a
	extz wa
	sla wa, 2
	lda_24 xbc, 0xee1130
	st_dri3b B, 0x07, 0xE4, 0xE0
	ld xwa, xiz
	ld bc, (xsp + 4)
	ld xix, (xde)
	call (xix)
	ld xwa, (xsp + 14)
	ld (xwa), hl
	ld c, (xiz + 6)
	cpl c
	ld xwa, (xsp + 22)
	and (xwa + 3), c
	jr SndParam_RW_Success

SndParam_RW_HandleB1Type:
	ld xwa, (xsp + 10)
	ld c, (xwa)
	res 7, c
	extz bc
	ld xwa, (xsp + 6)
	ld a, (xwa)
	res 7, a
	extz wa
	sla wa, 7
	ld de, wa
	or de, bc
	ld xwa, (xsp + 14)
	ld (xwa), de

SndParam_RW_Success:
	lds hl, 0
	jr SndParam_RW_Epilogue

SndParam_RW_Fail:
	ldw hl, 0xFFFF

SndParam_RW_Epilogue:
	pop xiz
	lda xsp, (xsp + 22)
	ret

