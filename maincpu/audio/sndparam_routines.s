SndParam_RW_ChainNext:
	ld xde, (xde + 8)
	ld xix, xiz
	ld xiy, (xde)
	ldw hl, 0xFFFF
	ld xwa, xiy
	srl xwa, 8
	cp xbc, xwa
	jr nz, SndParam_RW_ChainCheckFirst
	ld xwa, xix
	srl xwa, 0
	cp xwa, 0xB1
	jr z, SndParam_RW_ChainExactMatch
	ld xwa, xiy
