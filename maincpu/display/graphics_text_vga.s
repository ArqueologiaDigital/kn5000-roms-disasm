.macro _VGA_WRITE regnum, value
	.if \regnum <= 7
	lds wa, \regnum
	.else
	ldw wa, \regnum
	.endif
	.if \value <= 7
	lds bc, \value
	.else
	ldw bc, \value
	.endif
	calr _Write_VGA_Register
.endm


.macro _VGA_READ regnum
	.if \regnum <= 7
	lds wa, \regnum
	.else
	ldw wa, \regnum
	.endif
	calr _Read_VGA_Register
.endm


