READ_COM_SELECT_SWITCH:		; FCF8F6
	LD A, (PZ:16)
	SRL 4, A
	LD XIX, OFFSETS_FCF90C
	LD A, (XIX + A)
	LD (COM_SELECT), A
	RET

; Input: Active-low "COM_SELECT"
; bit 7: MIDI
; bit 6: MAC
; bit 5: PC1
; bit 4: PC2
;
; Output:
;   000h = MIDI
;   001h = MAC
;   002h = PC1
;   003h = PC2
;
; Note: Bad switch positioning data (more than a single low-bit)
;       is treated as MIDI selection.
;
OFFSETS_FCF90C:
	db 000h
	db 000h
	db 000h
	db 000h
	db 000h
	db 000h
	db 000h
	db 000h  ; MIDI
	db 000h
	db 000h
	db 000h
	db 001h  ; MAC
	db 000h
	db 002h  ; PC1
	db 003h  ; PC2
	db 000h

