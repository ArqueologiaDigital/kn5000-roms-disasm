; FDC command dispatcher
; Reads command from (8A40h), dispatches to 12 handlers (0-0xB)
; Uses offset table at 0xEA98B2
FDC_COMMAND_DISPATCHER:	; F96DB1
	.byte 0xfa	; LD (8A2Ah), 000h
	.byte 0xeb, 0xa8	; LD WA, (8A40h)
	.byte 0x68, 0x67	; CP WA, 000bh
	.byte 0xaf, 0x12, 0x20	; JR UGT, FDC_CheckDriveCount
	.byte 0xaf, 0x0e, 0x21	; ADD WA, WA
	.byte 0xaf, 0x0a, 0x22	; LDA XIX, 0EA98B2h
	.byte 0x68, 0x58	; LD WA, (XIX + WA)
	.byte 0xaf, 0x12, 0x20	; LDA XIX, FDC_CMD_HANDLER_BASE
	.byte 0x1d, 0x66, 0x62, 0xfa	; JP T, XIX + WA
; FDC command handler base - entry point for command 0
FDC_CMD_HANDLER_BASE:	; F96DD6
	.byte 0xeb, 0x8e	; CALR FDC_SetupFormatParams
	.byte 0xae, 0x28, 0x20	; LD L, (8A24h)
	.byte 0xe8, 0xcf, 0xff, 0xff, 0xff, 0xff	; RET

