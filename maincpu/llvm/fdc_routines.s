	ld XHL, (0x8a4c)
	LDC_DMAS3_XHL
	ld XHL, FDC__DMA_ACKNOWLEDGE
	LDC_DMAD3_XHL
	LD_A 8
	LDC_DMAM3_A
	jr FDC_Port_Reset_Or_Noop
	ld BC, (0x8a1c)
	LDC_DMAC3_BC
	ret

