	ld (0x8A3D), 0x0
	ld (0x8A3E), 0x0
	ld (0x8A3F), 0x0
	ld (0x8A3A), 0x0
	ret

FDC_CheckHead:
	ld WA, (0x8A44)
	ld (0x8A2C), A
	ld (0x8A29), A
	cp (0x8A29), 0x0
	ret Z
	cp (0x8A29), 0x1
	ret Z
	ld WA, 0xfe
	CALR FDC_Set_Status
	ret

FDC_Command5_Epilogue:
	ret

FDC_Validate_Drive_Head:
	cpw (0x8A44), 0x0
	ret Z
	cpw (0x8A44), 0x1
	ret Z
	ld WA, 0xfe
	CALR FDC_Set_Status
	ret


FDC_NOP_Delay:
	dec 2, XSP
	ld (XSP), A
	ld A, (XSP)
	dec 1, (XSP)
	cp A, 0
	jr Z, FDC_NOP_Delay_Exit

