; FDC command dispatcher
; Reads command from (8A40h), dispatches to 12 handlers (0-0xB)
; Uses offset table at 0xEA98B2
FDC_COMMAND_DISPATCHER:	; F96DB1
	ld (0x8A2A), 0x0
	ld WA, (0x8A40)
	cp WA, 0xb
	jr UGT, FDC_CheckDriveCount
	add WA, WA
	lda XIX, 0xEA98B2
	ld WA, (XIX + WA)
	lda XIX, FDC_CMD_HANDLER_BASE
	jp XIX + WA
; FDC command handler base - entry point for command 0
FDC_CMD_HANDLER_BASE:	; F96DD6
	CALR FDC_SetupFormatParams
	ld L, (0x8A24)
	ret

FDC_ReturnZero:
	LD_L 0x0
	ret

FDC_ErrorInvalidDrive:
	CALR FDC_Validate_Drive_Head

FDC_CheckDriveCount:
	ld WA, (0x8A42)
	ld (0x8A2A), A
	cp (0x8A2A), 0x1
	jr ULE, FDC_ValidateCommand
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_ValidateCommand:
	ld WA, (0x8A40)
	cp WA, 4
	jr Z, FDC_ValidateTrack
	cp WA, 3
	jr Z, FDC_ValidateTrack
	cp WA, 2
	jr Z, FDC_ValidateTrack
	cp WA, 5
	jr Z, FDC_Command5Handler
	cp WA, 0xb
	jr Z, FDC_NoOpReturn
	cp WA, 1
	jr NZ, FDC_ValidateTrack

FDC_NoOpReturn:
	LD_L 0x0
	ret

FDC_Command5Handler:
	CALR FDC_Command5_Epilogue
	ld L, (0x8A24)
	ret

FDC_ValidateTrack:
	ld WA, (0x8A46)
	ld (0x8A2B), A
	ld (0x8A36), A
	extz WA
	cp WA, (0x8B08)
	jr C, FDC_HandleCmd2
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_HandleCmd2:
	cpw (0x8A40), 0x2
	jr NZ, FDC_CheckSectorCount
	CALR FDC_CheckHead
	ld L, (0x8A24)
	ret

FDC_CheckSectorCount:
	cpw (0x8A4A), 0x0
	jr NZ, FDC_CheckSectorNum
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_CheckSectorNum:
	ld WA, (0x8A48)
	ld (0x8A2D), A
	cp (0x8A2D), 0x0
	jr NZ, FDC_CheckFormatType
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_CheckFormatType:
	ld A, (0x8A6C)
	cp A, 0
	jr Z, FDC_FormatDefault
	cp A, 5
	jr Z, FDC_FormatDefault
	cp A, 4
	jr Z, FDC_FormatType4
	cp A, 3
	jr Z, FDC_FormatType3
	cp A, 2
	jr NZ, FDC_ErrorInvalid
	cp (0x8A2D), 0x8
	jr ULE, FDC_ValidExecute
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_FormatType3:
	cp (0x8A2D), 0x12
	jr ULE, FDC_ValidExecute
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_FormatType4:
	cp (0x8A2D), 0xff
	jr NZ, FDC_Format4Check
	CALR FDC_CheckHead
	ld L, (0x8A24)
	ret

FDC_Format4Check:
	cp (0x8A2D), 0x9
	jr ULE, FDC_ValidExecute
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_FormatDefault:
	cp (0x8A2D), 0x9
	jr ULE, FDC_ValidExecute
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_ErrorInvalid:
	ld WA, 0xfe
	jrl FDC_Set_Status

FDC_ValidExecute:
	CALR FDC_CheckHead
	ld L, (0x8A24)
	ret

FDC_SetupFormatParams:
	ld WA, (0x8A46)
	ld (0x8A6E), A
	and A, 0xf
	cp A, 3
	jrl Z, FDC_Format1440K
	cp A, 2
	jr Z, FDC_FormatDD
	cp A, 5
	jr Z, FDC_FormatHD
	cp A, 4
	jr Z, FDC_FormatHD
	cp A, 0
	jrl NZ, FDC_FormatUnknown

