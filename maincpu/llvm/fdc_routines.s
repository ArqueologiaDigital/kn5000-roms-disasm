	ldw (0x8B08), 0x50
	ldw (0x8B0A), 0x12
	ldw (0x8B0C), 0x13
	jr FDC_InitStateVars

FDC_FormatUnknown:
	ld WA, 0xfe
	CALR FDC_Set_Status

FDC_InitStateVars:
	ld A, (0x8A6E)
	srl A, 4
	and A, 0xf
	ld (0x8A37), A
	ld (0x8A31), 0xff
	ld (0x8A34), 0x0
	ld (0x8A38), 0xf
	ld (0x8A39), 0x1
