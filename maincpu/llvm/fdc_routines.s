;   - Format parameter configuration
;   - Drive detection and status
;
; Address range: 0xF96D54 - 0xF98009
;
; Dependencies:
;   - fdc_constants.asm must be included before this file
;   - Requires FDC_MAP__BASE_ADDR and FDC__DMA_ACKNOWLEDGE
; =============================================================================

