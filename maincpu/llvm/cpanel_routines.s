	.byte 0xe2, 0x9a, 0x74, 0x02, 0xc0	; LD HL, 3	; SOFT VERSION SCREEN
	.byte 0xf2, 0xa2, 0x74, 0x02, 0x60	; JR T, LABEL_FC4193

