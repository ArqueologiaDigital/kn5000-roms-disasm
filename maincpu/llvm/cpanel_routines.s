CPanel_CheckSpecialCombos:
	.byte 0xe2, 0x9e, 0x74, 0x02, 0xc8	; CP (STATE_OF_CPANEL_BUTTONS_LEFT + 4), 06ch	;  CPL_SEG4 = 0110 1100 = AUTO PLAY CHORD + SPLIT POINT + VARIATION 4 + VARIATION 3 => display sw internal build numbers
