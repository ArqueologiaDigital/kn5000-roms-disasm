; FDC command dispatcher
; Reads command from (8A40h), dispatches to 12 handlers (0-0xB)
; Uses offset table at 0xEA98B2
FDC_COMMAND_DISPATCHER:	; F96DB1
	stdi8 35370, 0
	ldda16 xwa, 35392
	cp wa, 0xB
	jr ugt, FDC_CheckDriveCount
	add wa, wa
	ldada_24 xix, 15374514
	ld_wa_sriw3 0x07, 0xF0, 0xE0
	ldada_24 xix, 16346582
	x_dri4_sd8 0x07, 0xF0, 0xE0
; FDC command handler base - entry point for command 0
FDC_CMD_HANDLER_BASE:	; F96DD6
	calr FDC_SetupFormatParams
	ldda8 l, 35364
	ret

FDC_ReturnZero:
	ldb l, 0x0
	ret

FDC_ErrorInvalidDrive:
	calr FDC_Validate_Drive_Head

FDC_CheckDriveCount:
	ldda16 xwa, 35394
	stda8 35370, a
	cpdi8 35370, 1
	jr ule, FDC_ValidateCommand
	ldw wa, 0xFE
	jrl FDC_Set_Status

FDC_ValidateCommand:
	ldda16 xwa, 35392
	cps wa, 4
	jr z, FDC_ValidateTrack
	cps wa, 3
	jr z, FDC_ValidateTrack
	cps wa, 2
	jr z, FDC_ValidateTrack
	cps wa, 5
	jr z, FDC_Command5Handler
	cp wa, 0xB
	jr z, FDC_NoOpReturn
	cps wa, 1
	jr nz, FDC_ValidateTrack

FDC_NoOpReturn:
	ldb l, 0x0
	ret

FDC_Command5Handler:
	calr FDC_Command5_Epilogue
	ldda8 l, 35364
	ret

FDC_ValidateTrack:
	ldda16 xwa, 35398
	stda8 35371, a
	stda8 35382, a
	extz wa
	cpda16 xwa, 35592
	jr c, FDC_HandleCmd2
	ldw wa, 0xFE
	jrl FDC_Set_Status

FDC_HandleCmd2:
	cpdi16 35392, 2
	jr nz, FDC_CheckSectorCount
	calr FDC_CheckHead
	ldda8 l, 35364
	ret

FDC_CheckSectorCount:
