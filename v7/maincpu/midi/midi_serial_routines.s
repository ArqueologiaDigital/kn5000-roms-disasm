; Hardware:
;   Serial Channel 0 (SC0) registers:
;     SC0BUF (0xd0) - Serial buffer
;     SC0CR  (0xd1) - Control register
;     SC0MOD (0xd2) - Mode register
;     BR0CR  (0xd3) - Baud rate control
;
; COM_SELECT switch values:
;   0x00 = MIDI
;   0x01 = MAC
;   0x02 = PC1
;   0x03 = PC2
;
; =============================================================================

