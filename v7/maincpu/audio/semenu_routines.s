SeMenu_SendEvent:
	dec 2, xsp
	ld (xsp), c
	cp (xsp), 0x0
	jr nz, SeMenu_SendEvent_Indirect
	extz wa
	call UI_PostModeChangeEvent
	jr SeMenu_SendEvent_StoreAndReturn

SeMenu_SendEvent_Indirect:
	call UI_PostRefreshEvent

SeMenu_SendEvent_StoreAndReturn:
	ld a, (xsp)
	extz wa
	calr SeMenu_StoreEventId
	inc 2, xsp
	ret

