Sound_Navigate_Entry:
	ld (xsp + 4), wa
	cpw (xsp + 4), 0xf
	jr le, Sound_Navigate_Init
	cpw (xsp + 4), 0x15
	jrl lt, Sound_Navigate_Return
	cpw (xsp + 4), 0x16
	jrl gt, Sound_Navigate_Return

Sound_Navigate_Init:
	ldw (xsp + 12), 0x0

	ld xwa, (xsp + 20)

	srl xwa, 0

	ldiw_erp 0xe2, 0

	ld (xsp + 10), wa

	ld wa, (xsp + 4)

	lds bc, 0

	.byte 0x1d, 0x26, 0xcd, 0xfc	; call SndParam_LookupViaEncode (v7 addr)

	ld (xsp + 17), l

	ld wa, (xsp + 4)

	ldw bc, 0x20

	.byte 0x1d, 0x26, 0xcd, 0xfc	; call SndParam_LookupViaEncode (v7 addr)

	lda xwa, (xsp + 14)

	ld (xwa + 4), l

	ld bc, (xsp + 4)

	ld (xwa + 2), c

	.byte 0x1d, 0x1b, 0xe0, 0xfe	; call SndParam_FetchOscTableEntry (v7 addr)

	lda xbc, (xsp + 14)

	ld a, (xbc)

	extz wa

	ld (xsp + 8), wa

	ld a, (xbc + 1)

	ldb_erp A, 0xf8

	extz iz

	ld wa, (xsp + 4)

	ld bc, (xsp + 8)

	.byte 0x1e, 0x2b, 0x01	; calr GetSoundBankCount (v7 displacement)

	ld (xsp + 6), hl

	add iz, (xsp + 10)



Sound_Navigate_SearchLoop:
	cps iz, 0
	jr ge, Sound_Navigate_ScanForward
	cpw (xsp + 8), 0x0
	jr le, Sound_Navigate_AtBottom
	ld wa, (xsp + 8)
	ldw_erp WA, 0xfa
	ld (xsp + 10), iz
	ld hl, (xsp + 6)
	cpiw_erp 0xfa, 0
	jrl le, Sound_Navigate_UpdateState

Sound_Navigate_ScanBackward:
	dec1w_erp 0xfa
	ld wa, (xsp + 4)
	stw_erp BC, 0xfa
	calr GetSoundBankCount
	ld wa, hl
	inc 1, wa
	add (xsp + 10), wa
	cp hl, 0xffff
	jr nz, Sound_Navigate_BackwardCheck
	cpiw_erp 0xfa, 0
	jr gt, Sound_Navigate_BackwardCheck
	ld wa, (xsp + 8)
	ldw_erp WA, 0xfa
	ldw (xsp + 10), 0x0
	ld hl, (xsp + 6)
	jr Sound_Navigate_UpdateState

Sound_Navigate_BackwardCheck:
	cp hl, 0xffff
	jr nz, Sound_Navigate_UpdateState
	cpiw_erp 0xfa, 0
	jr gt, Sound_Navigate_ScanBackward
	jr Sound_Navigate_UpdateState

Sound_Navigate_AtBottom:
	lds iz, 0
	jrl Sound_Navigate_SetDone

Sound_Navigate_ScanForward:
	cp iz, (xsp + 6)
	jrl le, Sound_Navigate_SetDone
	cpw (xsp + 8), 0x11
	jrl ge, Sound_Navigate_AtTop
	ld wa, (xsp + 8)
	ldw_erp WA, 0xfa
	ld (xsp + 10), iz
	ld hl, (xsp + 6)
	cp_erpw 0xfa, 0x11, 0x00
	jr ge, Sound_Navigate_UpdateState

Sound_Navigate_ForwardLoop:
	inc1w_erp 0xfa
	inc 1, hl
	sub (xsp + 10), hl
	ld wa, (xsp + 4)
	stw_erp BC, 0xfa
	calr GetSoundBankCount
	cp hl, 0xffff
	jr nz, Sound_Navigate_ForwardCheck
	cp_erpw 0xfa, 0x11, 0x00
	jr lt, Sound_Navigate_ForwardCheck
	ld wa, (xsp + 8)
	ldw_erp WA, 0xfa
	ld wa, (xsp + 6)
	ld (xsp + 10), wa
	ld hl, (xsp + 6)
	jr Sound_Navigate_UpdateState

Sound_Navigate_ForwardCheck:
	cp hl, 0xffff
	jr nz, Sound_Navigate_UpdateState
	cp_erpw 0xfa, 0x11, 0x00
	jr lt, Sound_Navigate_ForwardLoop

Sound_Navigate_UpdateState:
	stw_erp WA, 0xfa
	ld (xsp + 8), wa
	ld iz, (xsp + 10)
	ld (xsp + 6), hl
	cpw (xsp + 12), 0x0
	jrl z, Sound_Navigate_SearchLoop

Sound_Navigate_Commit:
	lda xbc, (xsp + 14)
	ld a, (xbc + 1)
	extz wa
	cp wa, iz
	jr nz, Sound_Navigate_ApplyChange
	ld a, (xbc)
	extz wa
	cp wa, (xsp + 8)
	jr z, Sound_Navigate_Return

Sound_Navigate_ApplyChange:
	ld wa, (xsp + 4)

	extz wa

	ld bc, (xsp + 8)

	extz bc

	stb_erp E, 0xf8

	extz de

	.byte 0x1d, 0x2e, 0x95, 0xfc	; call MIDI_DistributeParamToChannels (v7 addr)

	ld wa, (xsp + 4)

	extz wa

	ld bc, (xsp + 8)

	ld e, c

	extz de

	stb_erp C, 0xf8

	extz bc

	pushw bc

	lds bc, 0

	.byte 0x1d, 0x84, 0xaa, 0xfd	; call SwbtWr (v7 addr)

	lds wa, 1



Sound_Navigate_Notify:
	call BitMapOut_StorePresetValue

Sound_Navigate_Return:
	lds32 xhl, 0
	pop xiz
	lda xsp, (xsp + 20)
	ret

Sound_Navigate_AtTop:
	ld iz, (xsp + 6)

Sound_Navigate_SetDone:
	ldw (xsp + 12), 0x1
	jr Sound_Navigate_Commit

GetSoundBankCount:
	ld de, bc
	ld hl, wa
	ld a, l
	ld c, e
	extz bc
	extz wa
	cp hl, 0xf
	jr z, GetSoundBankCount_CheckDrum
	cps hl, 2
	jr z, GetSoundBankCount_StandardBank
	cps hl, 1
	jr z, GetSoundBankCount_StandardBank
	cps hl, 0
	jr nz, GetSoundBankCount_CheckSpecial

GetSoundBankCount_StandardBank:
	jr GetSoundBankCount_DoLookup

GetSoundBankCount_CheckDrum:
	cp de, 0xf
	jr z, GetSoundBankCount_DoLookup

GetSoundBankCount_Invalid:
	ldw hl, 0xffff

GetSoundBankCount_Return:
	ret

GetSoundBankCount_CheckSpecial:
	cp de, 0xc
	jr z, GetSoundBankCount_Invalid

GetSoundBankCount_DoLookup:
