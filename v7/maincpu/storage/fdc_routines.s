	.byte 0xf2, 0x08, 0x00, 0x11, 0x41, 0x0e, 0xc1, 0x86
	.byte 0x8a, 0x19, 0x84, 0x8a, 0xf1, 0x86, 0x8a, 0x41
	.byte 0x0e
FDC_Write_Data:
	stb_da (0x11000a), a
	ret

