RVari_Select_CalcVisibleCount:
	ld (xsp + 4), 0x9
	ld xbc, (xiz + 52)
	ld xwa, (xiz + 44)
	ld wa, (xwa)
	muls wa, 0xa
	dec 1, wa
	ld bc, (xbc)
	sub bc, wa
	jr ge, RVari_Select_CheckTypeE
	ld xbc, (xiz + 52)
	ld xwa, (xiz + 44)
	ld wa, (xwa)
	muls wa, 0xa
	dec 1, wa
	sub wa, (xbc)
	ldw bc, 0x9
	sub bc, wa
	ld (xsp + 4), c

RVari_Select_CheckTypeE:
	ld xwa, (xiz + 56)
	cpw (xwa), 0xe
	jrl nz, RVari_Select_TypeNotE
	ld xbc, (xiz + 44)
	ld xwa, (xiz + 64)
	ld wa, (xwa)
	exts xwa
	divs wa, 0xa
	exts xwa
	divs wa, 0x4
	inc 1, wa
	cp wa, (xbc)
	jrl nz, RVari_Select_OtherItem
	ld c, (xsp + 4)
	srl c, 1
	extz bc
	sla bc, 2
	lda_24 xde, (0x03f214)
	ld xwa, (xiz + 64)
	ld wa, (xwa)
	exts xwa
	divs wa, 0x4
	exts xwa
	divs wa, 0xa
	stw_erp HL, 0xe2
	ld_sril3 XWA, 0x07, 0xe8, 0xe4
	ldb_sri A, 0x07, 0xe0, 0xec
	extz wa
	stb_dri A, 0xfd, 0x14, 0x02
	call GetEditSwPoint
	stb_dri B, 0xfd, 0x18, 0x02
	stb_dri C, 0xfd, 0x14, 0x02
	lda xbc, (xhl + 2)
	ld wa, (xbc)
	sub wa, 0xf
	ld (xde + 2), wa
	ld wa, (xbc)
	add wa, 0x10
	ld (xde + 6), wa
	cpw (xhl), 0x0
	jr nz, RVari_SelectE_FirstItem_NotFirst
	stb_dri W, 0xfd, 0x18, 0x02
	ldw (xwa), 0x8
	ldw (xwa + 4), 0x9c
	jr RVari_SelectE_FirstItem_Draw

