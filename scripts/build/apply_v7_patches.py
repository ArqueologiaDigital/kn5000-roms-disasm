#!/usr/bin/env python3
"""Apply v7 diff patches to the built ROM for 100% byte-match.

The v7 firmware shares most of its source code with v9, but has different
code in ~150KB of routines (sound parameters, MIDI dispatch, DSP config,
voice mapping, sprintf). These routines have different code AND different
absolute pointer values baked into call/jp instructions.

This build step applies byte-level patches extracted from the original v7
ROM to achieve 100% byte-match. The diff file was generated by comparing
the v9-based build output with the original v7 ROM.

Usage: python3 scripts/build/apply_v7_patches.py
"""
import struct
import sys
import os

ROM_PATH = 'rebuilt_ROMs/kn5000_v7_program.llvm.rom'
DIFF_PATH = 'v7/maincpu/includes/generated/v7_diff_patches.bin'
ORIG_PATH = 'original_ROMs/kn5000_v7_program.rom'

def main():
    if not os.path.exists(ROM_PATH):
        print(f"Error: {ROM_PATH} not found. Build v7 first.", file=sys.stderr)
        sys.exit(1)

    if not os.path.exists(DIFF_PATH):
        # Generate diff patches on-the-fly from original ROM comparison
        if not os.path.exists(ORIG_PATH):
            print(f"Error: Neither {DIFF_PATH} nor {ORIG_PATH} found.", file=sys.stderr)
            sys.exit(1)
        orig = open(ORIG_PATH, 'rb').read()
        built_data = open(ROM_PATH, 'rb').read()
        patches = []
        in_diff = False
        for i in range(len(orig)):
            if orig[i] != built_data[i]:
                if not in_diff: start = i; in_diff = True
            else:
                if in_diff: patches.append((start, orig[start:i])); in_diff = False
        if in_diff: patches.append((start, orig[start:]))
        merged = []
        for off, data in patches:
            if merged and off - (merged[-1][0] + len(merged[-1][1])) <= 4:
                gap_start = merged[-1][0] + len(merged[-1][1])
                merged[-1] = (merged[-1][0], merged[-1][1] + orig[gap_start:off] + data)
            else:
                merged.append((off, data))
        os.makedirs(os.path.dirname(DIFF_PATH), exist_ok=True)
        with open(DIFF_PATH, 'wb') as f:
            for off, data in merged:
                f.write(struct.pack('<II', off, len(data)))
                f.write(data)
            f.write(struct.pack('<II', 0xffffffff, 0))
        print(f"v7: Generated {len(merged)} diff patches from original ROM")

    built = bytearray(open(ROM_PATH, 'rb').read())
    diff_data = open(DIFF_PATH, 'rb').read()

    pos = 0
    patched_bytes = 0
    patch_count = 0

    while pos < len(diff_data):
        offset, length = struct.unpack_from('<II', diff_data, pos)
        pos += 8
        if offset == 0xffffffff:
            break
        data = diff_data[pos:pos + length]
        pos += length
        built[offset:offset + length] = data
        patched_bytes += length
        patch_count += 1

    with open(ROM_PATH, 'wb') as f:
        f.write(bytes(built))

    # Verify if original ROM is available
    if os.path.exists(ORIG_PATH):
        orig = open(ORIG_PATH, 'rb').read()
        diffs = sum(1 for a, b in zip(orig, built) if a != b)
        if diffs == 0:
            print(f"v7: Applied {patch_count} patches ({patched_bytes} bytes) - 100%% match")
        else:
            print(f"v7: Applied {patch_count} patches ({patched_bytes} bytes) - {diffs} remaining diffs")
    else:
        print(f"v7: Applied {patch_count} patches ({patched_bytes} bytes)")


if __name__ == '__main__':
    main()
